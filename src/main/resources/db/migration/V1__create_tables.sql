CREATE TABLE director
(
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name  VARCHAR(255) NOT NULL
);

CREATE TABLE division
(
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    director_id   bigint       NOT NULL REFERENCES director (id),
    parent_id     bigint REFERENCES division (id)
);

CREATE TABLE zipcode
(
    zip   VARCHAR(20) PRIMARY KEY,
    label VARCHAR(255) NOT NULL
);

CREATE TABLE license_plate
(
    plate_number VARCHAR(50) PRIMARY KEY,
    country      VARCHAR(100) NOT NULL
);

CREATE TABLE contact_person
(
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    mobile_phone VARCHAR(50),
    telephone    VARCHAR(50),
    email        VARCHAR(255) NOT NULL,
    address      VARCHAR(255),
    zip          VARCHAR(20) REFERENCES zipcode (zip)
);

CREATE TABLE parking_lot
(
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255)   NOT NULL,
    category          VARCHAR(50)    NOT NULL,
    max_capacity      INTEGER        NOT NULL,
    price_per_hour    NUMERIC(10, 2) NOT NULL,
    contact_person_id bigint         NOT NULL REFERENCES contact_person (id),
    division_id       bigint         NOT NULL REFERENCES division (id),
    address           VARCHAR(255),
    zip               VARCHAR(20) REFERENCES zipcode (zip)
);

CREATE TABLE member
(
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name           VARCHAR(255) NOT NULL,
    last_name            VARCHAR(255) NOT NULL,
    telephone            VARCHAR(50),
    email                VARCHAR(255) NOT NULL,
    address              VARCHAR(255),
    zip                  VARCHAR(20) REFERENCES zipcode (zip),
    license_plate_number VARCHAR(50)  NOT NULL REFERENCES license_plate (plate_number),
    registration_date    DATE         NOT NULL,
    membership_level     VARCHAR(20)  NOT NULL
);

CREATE TABLE parking_allocation
(
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id            bigint      NOT NULL REFERENCES member (id),
    parking_lot_id       bigint      NOT NULL REFERENCES parking_lot (id),
    license_plate_number VARCHAR(50) NOT NULL
);